"""simulation_launch.py — Launch the CPU MuJoCo simulator (FIC Studio's default).

Same arguments as `mujoco_newton/launch/simulation_launch.py`, so the Studio
switches between the CPU and the optional GPU backend with a single setting.

Unlike the Newton backend this does NOT use launch_ros' Node action: the MuJoCo
passive viewer on macOS must run under the `mjpython` interpreter (which owns the
Cocoa run loop), so we invoke the installed entry-point script directly with the
right interpreter via ExecuteProcess. Pass `headless:=true` to disable the viewer,
in which case a plain `python3` is used (works over SSH / in CI).

Usage:
    ros2 launch mujoco_native simulation_launch.py robot_name:=Franka_FR3
    ros2 launch mujoco_native simulation_launch.py robot_name:=KinovaGen3_7DOF headless:=true
    ros2 launch mujoco_native simulation_launch.py robot_name:=MyArm model_file:=/abs/scene.xml

model_file overrides the built-in map; FIC Studio always passes it, so robots
imported from a URDF need no entry here and no rebuild.
"""

import os
import sys

from ament_index_python.packages import get_package_prefix, get_package_share_path
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.actions import ExecuteProcess
from launch.substitutions import LaunchConfiguration


# Built-in robot -> MJCF map (mujoco_newton keeps a subset) — keep in sync.
_ROBOT_XML = {
    "KinovaGen3_7DOF": "model/KinovaGen3_7DOF/xml/scene.xml",
    "KinovaGen3_CSPM": "model/KinovaGen3_CSPM/xml/scene.xml",
    "Franka_FR3":      "model/Franka_FR3/xml/scene.xml",
    "IIWA_14":         "model/IIWA_14/XML/scene.xml",
    "Pendulum":        "model/Pendulum/xml/pendulum.xml",
    # CSPM — coaxial spherical parallel manipulator: XML-only (no URDF),
    # closed-loop (3 <equality><connect> constraints), 3 actuated of 9 hinges.
    "CSPM":            "model/CSPM/xml/coaxial_spm.xml",
    # Spot — quadruped: floating base (freejoint), 12 actuated hinges,
    # torque actuators torq_j1..torq_j12. Driven by the fic_locomotion node.
    "Spot":            "model/Spot/xml/scene.xml",
    "leg_spherical":      "model/leg_spherical/xml/leg_spherical.xml",
    # leg_spherical_quad - four cable-driven legs on a floating trunk,
    # 12 torque actuators torq_j1..12, generated by build_quad.py.
    "leg_spherical_quad": "model/leg_spherical_quad/xml/leg_spherical_quad.xml",
    "human":      "model/ms_human_700/scene.xml",


}


def _resolve_xml(context) -> str:
    robot_name = LaunchConfiguration("robot_name").perform(context)
    model_file = LaunchConfiguration("model_file").perform(context)
    if model_file:
        if not os.path.isfile(model_file):
            raise ValueError(f"model_file not found: {model_file}")
        return model_file
    if robot_name not in _ROBOT_XML:
        raise ValueError(
            f"Unknown robot name: {robot_name}. "
            f"Supported: {list(_ROBOT_XML.keys())}; for any other robot pass "
            f"model_file:=/path/to/scene.xml")
    return os.path.join(get_package_share_path("menagerie"), _ROBOT_XML[robot_name])


def _sim_script() -> str:
    """Absolute path to the installed `simulation` entry-point script."""
    return os.path.join(
        get_package_prefix("mujoco_native"), "lib", "mujoco_native", "simulation")


def _configure(context, *_, **__):
    xml_file = str(_resolve_xml(context))
    headless = LaunchConfiguration("headless").perform(context).lower() in ("1", "true", "yes")
    sid = LaunchConfiguration("station_id").perform(context)
    topic_prefix = f"robot{sid}_simulation"

    # The passive viewer needs mjpython on macOS; headless runs fine under
    # plain python. On Linux the mujoco wheel's viewer works under python too,
    # so mjpython is only strictly required for the macOS viewer path.
    if sys.platform == "darwin" and not headless:
        interpreter = "mjpython"
    else:
        interpreter = "python3"

    cmd = [
        interpreter, _sim_script(),
        "--ros-args",
        "-r", f"__node:=simulation_mujoco_native_{sid}",
        "-p", f"simulation/model_file:={xml_file}",
        "-p", f"topic_prefix:={topic_prefix}",
        "-p", f"headless:={'true' if headless else 'false'}",
    ]
    # Physics step and state rate: empty -> the node's defaults (the MJCF's
    # own timestep; joint_states + gravity_torques at 1 kHz).
    for arg in ("sim_dt", "publish_rate_hz"):
        value = LaunchConfiguration(arg).perform(context).strip()
        if value:
            cmd += ["-p", f"{arg}:={float(value)}"]
    # Start pose of a fixed-base arm (comma-separated rad); empty -> qpos0.
    initial = LaunchConfiguration("initial_joint_positions").perform(context).strip()
    if initial:
        cmd += ["-p", f"initial_joint_positions:='{initial}'"]

    # macOS: `ros2 launch` does NOT propagate DYLD_LIBRARY_PATH to the process
    # it spawns, so the rosidl Python typesupport .so — whose baked @rpath
    # points at the conda prefix, not the workspace — fails to dlopen the
    # message libs (`communication`), and the node dies at the first
    # create_subscription. AMENT_PREFIX_PATH *does* survive, so rebuild the
    # loader path from it (each prefix/lib holds that package's dylibs) and
    # inject it explicitly. No-op on Linux (which uses LD_LIBRARY_PATH and
    # already works).
    extra_env = _macos_dyld_env() if sys.platform == "darwin" else {}

    sim_proc = ExecuteProcess(
        cmd=cmd,
        name=f"simulation_mujoco_native_{sid}",
        output="screen",
        emulate_tty=True,
        additional_env=extra_env,
    )
    return [sim_proc]


def _macos_dyld_env() -> dict:
    """Reconstruct DYLD_LIBRARY_PATH from AMENT_PREFIX_PATH + conda prefix."""
    parts = []
    existing = os.environ.get("DYLD_LIBRARY_PATH", "")
    if existing:
        parts.append(existing)
    for prefix in os.environ.get("AMENT_PREFIX_PATH", "").split(os.pathsep):
        libdir = os.path.join(prefix, "lib")
        if prefix and os.path.isdir(libdir) and libdir not in parts:
            parts.append(libdir)
    conda = os.environ.get("CONDA_PREFIX")
    if conda:
        parts.append(os.path.join(conda, "lib"))
    return {"DYLD_LIBRARY_PATH": os.pathsep.join(parts)} if parts else {}


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument(
            "robot_name",
            default_value="KinovaGen3_7DOF",
            description=f"One of {list(_ROBOT_XML.keys())}"),
        DeclareLaunchArgument(
            "station_id",
            default_value="1",
            description="Station ID (1-4): scopes simulation topics"),
        DeclareLaunchArgument(
            "headless",
            default_value="false",
            description="Disable the MuJoCo viewer (useful over SSH / in CI). "
                        "When false on macOS the node is launched via mjpython."),
        DeclareLaunchArgument(
            "model_file",
            default_value="",
            description="Absolute path to a MuJoCo scene; overrides robot_name's "
                        "built-in model"),
        DeclareLaunchArgument(
            "sim_dt",
            default_value="",
            description="Physics step in seconds; empty = the MJCF's own timestep"),
        DeclareLaunchArgument(
            "publish_rate_hz",
            default_value="",
            description="joint_states/gravity_torques rate; empty = 1000 "
                        "(capped by the physics rate)"),
        DeclareLaunchArgument(
            "initial_joint_positions",
            default_value="",
            description="Start pose of a fixed-base arm: comma-separated angles "
                        "(rad) of its first joints; empty = all joints at 0"),
        OpaqueFunction(function=_configure),
    ])
