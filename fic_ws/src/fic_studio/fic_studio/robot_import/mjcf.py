"""Turn a prepared URDF into the MuJoCo model the FIC simulator drives.

MuJoCo imports the URDF itself (bodies, joints, limits, inertias, meshes). On
top of that this adds what FIC needs and a URDF cannot say:

* one ``<motor>`` per arm joint named ``torq_j1..N`` -- fic_control
  publishes commands to those names, in joint order;
* a ``force_torque_site`` on the end-effector body with ``force_sensor`` and
  ``torque_sensor`` -- the simulator's wrench publisher looks for them;
* a 1 kHz ``implicitfast`` integrator, a little joint armature, and
  self-collision switched off, because exported CAD meshes overlap at every
  joint and would otherwise make the arm shake;
* joint damping as heavy as FIC's hand-made models use (they have 45), scaled
  to each joint's torque so full torque still moves it at ~0.9 rad/s: the
  simulator starts before the controller, and an undamped arm falls and
  spins its wrist past a full turn in those seconds, which the controller
  then refuses as out of range;
* a ``home`` keyframe, so the viewer opens at the home pose;
* for a sliding-finger gripper, an actuator named ``gripper`` -- the one the
  Studio's gripper bridge commands -- with the fingers coupled like the
  URDF's ``<mimic>`` says.
"""
import itertools
import os
import re
import xml.etree.ElementTree as ET

import mujoco
import numpy as np

TIMESTEP = 0.001
ARMATURE = 0.01
DEFAULT_EFFORT = 50.0

#: Joint damping (N m s/rad) per N m of the joint's torque limit, and its cap
#: -- 45, what the hand-made Kinova and Franka models use.
DAMPING_PER_NM = 1.15
MAX_DAMPING = 45.0


def joint_damping(effort):
    """Damping for an arm joint with torque limit ``effort`` (N m)."""
    return round(min(MAX_DAMPING, DAMPING_PER_NM * (effort or DEFAULT_EFFORT)), 3)


#: The gripper bridge sends ctrl = BRIDGE_CTRL_PER_M x the width asked for
#: (its defaults: 0.085 m -> 0.85; Extensions/mujoco_playground/gripper_bridge.py).
BRIDGE_CTRL_PER_M = 10.0
GRIPPER_KP = 500.0          # N/m: a firm finger servo
GRIPPER_KV = 20.0           # N s/m: well damped for ~50 g fingers

SCENE_TEMPLATE = """<!--
  Scene for {model}: floor, light and sky around the robot in {robot_file}.
  Generated by FIC Control Studio's robot importer; same layout as
  menagerie/model/_template/xml/scene.xml.
-->
<mujoco model="{model} scene">
  <include file="{robot_file}"/>

  <statistic center="{center}" extent="{extent:.3f}"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="120" elevation="-20"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0"
      width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge"
      rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3" markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5"
      reflectance="0.2"/>
  </asset>

  <worldbody>
    <light pos="0 0 1.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>
  </worldbody>
</mujoco>
"""


class MjcfError(Exception):
    """The model could not be built; the message is written for the user."""


def compile_urdf(urdf_path):
    """Load a URDF (with a <mujoco><compiler/> block) into MuJoCo."""
    try:
        return mujoco.MjModel.from_xml_path(urdf_path)
    except ValueError as exc:
        text = str(exc).replace('Error: ', '').strip()
        hint = ''
        if 'mass and inertia' in text:
            hint = (' A moving link has no mass: give every link an <inertial> with '
                    'mass > 0, or check that its mesh loaded.')
        elif 'opening file' in text or 'could not open' in text.lower():
            hint = ' A mesh file could not be read.'
        raise MjcfError('MuJoCo could not load the robot: %s.%s' % (text, hint))


def _body_tree(root):
    """Map body name -> element, parent map, and robot bodies under worldbody."""
    world = root.find('worldbody')
    bodies, parent = {}, {}
    for b in world.iter('body'):
        bodies[b.get('name')] = b
        for child in b.findall('body'):
            parent[child.get('name')] = b.get('name')
    return world, bodies, parent


def build_robot_xml(raw_xml_path, out_xml_path, *, model_name, arm_joints, efforts,
                    ee_body, home_qpos, gripper=None):
    """Post-process MuJoCo's saved URDF import into the FIC robot file.

    ``home_qpos`` is the full position vector in the compiled model's own
    order (see ``home_qpos()``), so the keyframe is right even when the
    joint order differs from the arm's. ``gripper`` is an importer
    ``GripperPlan`` (or None).
    """
    tree = ET.parse(raw_xml_path)
    root = tree.getroot()
    root.set('model', model_name)

    comp = root.find('compiler')
    if comp is None:
        comp = ET.SubElement(root, 'compiler')
    comp.set('angle', 'radian')
    comp.set('meshdir', 'assets')
    comp.set('autolimits', 'true')

    for old in root.findall('option'):
        root.remove(old)
    option = ET.Element('option', timestep=str(TIMESTEP), integrator='implicitfast')
    root.insert(list(root).index(comp) + 1, option)

    default = root.find('default')
    if default is None:
        default = ET.Element('default')
        root.insert(list(root).index(option) + 1, default)
    joint_default = default.find('joint')
    if joint_default is None:
        joint_default = ET.SubElement(default, 'joint')
    joint_default.set('armature', str(ARMATURE))

    world, bodies, parent = _body_tree(root)

    # Collision geoms duplicate the visual ones on most exported robots; keep
    # them colliding but hide them in group 3 when the body is also drawn.
    for body in bodies.values():
        geoms = body.findall('geom')
        drawn = any(g.get('contype') == '0' and g.get('conaffinity') == '0' for g in geoms)
        for g in geoms:
            if drawn and not (g.get('contype') == '0' and g.get('conaffinity') == '0'):
                g.set('group', '3')

    joints = {j.get('name'): j for j in world.iter('joint')}
    for name, effort in zip(arm_joints, efforts):
        j = joints.get(name)
        if j is None:
            raise MjcfError('Joint %r is missing from the MuJoCo model.' % name)
        urdf = float(j.get('damping', 0) or 0)      # from the URDF's <dynamics>
        j.set('damping', '%g' % max(urdf, joint_damping(effort)))

    if ee_body not in bodies:
        raise MjcfError('The end-effector link %r is not a body in the MuJoCo model.' % ee_body)
    ET.SubElement(bodies[ee_body], 'site', name='force_torque_site', size='0.01',
                  rgba='1 0 0 1', group='4')

    # The robot never collides with itself in simulation (see module doc).
    names = sorted(bodies)
    if len(names) > 1:
        contact = root.find('contact')
        if contact is None:
            contact = ET.SubElement(root, 'contact')
        for a, b in itertools.combinations(names, 2):
            ET.SubElement(contact, 'exclude', body1=a, body2=b)

    for old in root.findall('actuator'):
        root.remove(old)
    actuator = ET.SubElement(root, 'actuator')
    for i, (joint, effort) in enumerate(zip(arm_joints, efforts)):
        e = effort if effort and effort > 0 else DEFAULT_EFFORT
        ET.SubElement(actuator, 'motor', name='torq_j%d' % (i + 1), joint=joint,
                      ctrlrange='%g %g' % (-e, e), ctrllimited='true')
    if gripper is not None:
        _add_gripper(root, actuator, gripper)

    sensor = root.find('sensor')
    if sensor is None:
        sensor = ET.SubElement(root, 'sensor')
    ET.SubElement(sensor, 'force', name='force_sensor', site='force_torque_site')
    ET.SubElement(sensor, 'torque', name='torque_sensor', site='force_torque_site')

    keyframe = ET.SubElement(root, 'keyframe')
    ET.SubElement(keyframe, 'key', name='home', qpos=' '.join('%.6g' % q for q in home_qpos))

    ET.indent(tree, space='  ')
    header = ("<!--\n  %s: generated by FIC Control Studio's robot importer from its URDF.\n"
              '  Motors torq_j1..%d drive the arm joints in order; force_torque_site on\n'
              '  %s carries the wrench sensors. Re-import the URDF rather than editing\n'
              '  this by hand, or edit freely and keep a copy.\n-->\n'
              % (model_name, len(arm_joints), ee_body))
    with open(out_xml_path, 'w') as fh:
        fh.write(header + ET.tostring(root, encoding='unicode') + '\n')


def _add_gripper(root, actuator, g):
    """Drive the fingers from the bridge's ctrl: width = ctrl / BRIDGE_CTRL_PER_M.

    A position servo on the driving finger, as a general actuator so the
    zero of its ctrl can sit at the finger's closed end:
    force = kp * (lower + ctrl / scale - q) - kv * qdot, with
    scale = BRIDGE_CTRL_PER_M * fingers (each finger moves its share).
    """
    scale = BRIDGE_CTRL_PER_M * g.fingers
    ET.SubElement(
        actuator, 'general', name='gripper', joint=g.driver,
        gaintype='fixed', biastype='affine',
        gainprm='%g' % (GRIPPER_KP / scale),
        biasprm='%g %g %g' % (GRIPPER_KP * g.lower, -GRIPPER_KP, -GRIPPER_KV),
        ctrlrange='0 %g' % (scale * (g.upper - g.lower)), ctrllimited='true',
        forcerange='%g %g' % (-g.effort, g.effort), forcelimited='true')
    if g.followers:
        equality = root.find('equality')
        if equality is None:
            equality = ET.SubElement(root, 'equality')
        for joint, multiplier, offset in g.followers:
            ET.SubElement(equality, 'joint', joint1=joint, joint2=g.driver,
                          polycoef='%g %g 0 0 0' % (offset, multiplier))


def home_qpos(model, arm_joints, home_rad):
    """Full qpos for ``model`` with the arm joints at ``home_rad``."""
    qpos = model.qpos0.copy()
    for name, q in zip(arm_joints, home_rad):
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name)
        if jid < 0:
            raise MjcfError('Joint %r is missing from the MuJoCo model.' % name)
        qpos[model.jnt_qposadr[jid]] = q
    return [float(v) for v in qpos]


def write_scene(out_dir, robot_file, model_name, center, extent, floor=True):
    """Write scene.xml around ``robot_file``; ``floor=False`` when the robot brings its own."""
    path = os.path.join(out_dir, 'scene.xml')
    text = SCENE_TEMPLATE.format(
        model=model_name, robot_file=robot_file,
        center=' '.join('%.3f' % c for c in center), extent=max(extent, 0.3))
    if not floor:
        text = re.sub(r'\n  <asset>.*?</asset>\n|\n  <worldbody>.*?</worldbody>\n', '\n', text,
                      flags=re.S)
    with open(path, 'w') as fh:
        fh.write(text)
    return path


def validate(scene_path, arm_joints, ee_body, home_rad, hold_s=0.5, ee_offset=None):
    """Load the scene and report what a user needs to know about it.

    Starts from the ``home`` keyframe when the model has one (a closed
    loop's is assembled), and holds it for ``hold_s`` seconds with gravity
    compensation: an arm with sane masses and joint axes stays put, so a
    large drift flags a model problem before FIC ever touches it.
    ``ee_offset`` (4x4) is the end-effector frame in ``ee_body``'s, when
    the two differ.
    """
    try:
        model = mujoco.MjModel.from_xml_path(scene_path)
    except ValueError as exc:
        raise MjcfError('The generated scene does not load: %s' % str(exc).replace('Error: ', ''))
    data = mujoco.MjData(model)
    qadr = [model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, j)]
            for j in arm_joints]
    kid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_KEY, 'home')
    if kid >= 0:
        mujoco.mj_resetDataKeyframe(model, data, kid)
    data.qpos[qadr] = home_rad
    data.ctrl[:] = 0.0
    mujoco.mj_forward(model, data)
    ee_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, ee_body)
    pose = np.eye(4)
    pose[:3, :3] = data.xmat[ee_id].reshape(3, 3)
    pose[:3, 3] = data.xpos[ee_id]
    if ee_offset is not None:
        pose = pose @ ee_offset
    ee_pos = pose[:3, 3].copy()
    quat = np.zeros(4)
    mujoco.mju_mat2Quat(quat, pose[:3, :3].flatten())
    w, x, y, z = quat
    for _ in range(int(hold_s / model.opt.timestep)):
        data.qfrc_applied[:] = data.qfrc_bias
        mujoco.mj_step(model, data)
    drift = float(np.degrees(np.max(np.abs(data.qpos[qadr] - np.asarray(home_rad))))) \
        if qadr else 0.0
    return {
        'bodies': int(model.nbody - 1),
        'joints': int(model.njnt),
        'actuators': int(model.nu),
        'meshes': int(model.nmesh),
        'mass_kg': float(model.body_subtreemass[0]),
        'ee_pos': [float(v) for v in ee_pos],
        'ee_quat_xyzw': [float(x), float(y), float(z), float(w)],
        'hold_drift_deg': drift,
        'finite': bool(np.all(np.isfinite(data.qpos))),
        'reach_m': float(np.linalg.norm(ee_pos)),
    }
