def _host():
    from PyQt5.QtWidgets import QLabel, QPushButton
    from fic_studio.mixins.robot_config_mixin import DEFAULT_ROBOT_CONFIGS, RobotConfigMixin

    class _Host(RobotConfigMixin):

        def __init__(self):
            self._page_title = lambda text: QLabel(text)  # noqa: E731
            self._btn = lambda text, style_id=None: QPushButton(text)  # noqa: E731
            self.robot_configs = copy.deepcopy(DEFAULT_ROBOT_CONFIGS)
            self.robot_dropdown = QComboBox()
            self.saves = self.syncs = 0

        def log_message(self, *a, **k):
            pass

        def _save_robot_configs(self):
            self.saves += 1

        def _sync_to_fic_config(self, show_result=False):
            self.syncs += 1

        def _refresh_robots_dropdown(self):
            pass

    host = _Host()
    host._test_page = host._build_robot_config_page()
    return host


class TestPageRegistersImport:

    def test_imported_robot_joins_list_and_both_files(self, tmp_path, model_root):
        host = _host()
        res = importer.create_robot(importer.analyse(make_package(str(tmp_path))), model_root)
        host._rc_register_imported_robot(res)
        assert host._rc_list_ids()[-1] == 'toy_arm'
        assert host._rc_current_id() == 'toy_arm'
        assert host.saves == 1 and host.syncs == 1
        assert host._rc_title_lbl.text() == 'Toy Arm'
        assert host._rc_has_gripper.isChecked()
        assert len(host._rc_home_fields) == 3
        assert host._rc_dirty is False

    def test_toolbar_follow_skips_while_editing(self):
        host = _host()
        host._rc_load_robot('Franka_FR3')
        host._rc_follow_toolbar('Pendulum')
        assert host._rc_current_id() == 'Pendulum'
        host._rc_display_name.setText('edited')
        host._rc_follow_toolbar('Franka_FR3')
        assert host._rc_current_id() == 'Pendulum'


class TestRobotListsRefresh:
    """A save refreshes every robot list without re-selecting the toolbar's robot."""

    def _items(self, combo):
        return [combo.itemText(i) for i in range(combo.count())]

    def test_save_does_not_churn_the_toolbar_selector(self):
        host = _host()
        host.robot_dropdown.addItems(list(host.robot_configs))
        host.robot_dropdown.setCurrentText('KinovaGen3_7DOF')
        seen = []
        host.robot_dropdown.currentTextChanged.connect(seen.append)
        host._rc_load_robot('Franka_FR3')
        host._rc_display_name.setText('renamed')
        host._rc_save()
        host.robot_configs['New_one'] = copy.deepcopy(host.robot_configs['Pendulum'])
        host._rc_refresh_robot_lists()
        assert seen == []                     # no slot ran: nothing was re-selected
        assert host.robot_dropdown.currentText() == 'KinovaGen3_7DOF'
        assert self._items(host.robot_dropdown)[-1] == 'New_one'
        assert host.robots['New_one'] == 1

    def test_deleting_the_selected_robot_moves_the_toolbar_on(self):
        host = _host()
        host.robot_dropdown.addItems(list(host.robot_configs))
        host.robot_dropdown.setCurrentText('Pendulum')
        seen = []
        host.robot_dropdown.currentTextChanged.connect(seen.append)
        del host.robot_configs['Pendulum']
        host._rc_refresh_robot_lists()
        assert seen == [host.robot_dropdown.currentText()] and seen[0] != 'Pendulum'

    def test_extra_card_type_lists_learn_new_robots(self):
        host = _host()
        host.robot_dropdown.addItems(list(host.robot_configs))
        host._card_robot_types = {'robot_2': 'Franka_FR3'}
        host.robot_2_type_dropdown = QComboBox()
        host.robot_2_type_dropdown.addItems(['Franka_FR3', 'Pendulum'])
        host.robot_2_type_dropdown.setCurrentText('Franka_FR3')
        host.robot_configs['New_one'] = copy.deepcopy(host.robot_configs['Pendulum'])
        host._rc_refresh_robot_lists()
        assert 'New_one' in self._items(host.robot_2_type_dropdown)
        assert host.robot_2_type_dropdown.currentText() == 'Franka_FR3'


class TestClosedLoopDialog:
    """The review screen for a five-bar: loops, driven ticks, the MuJoCo model row."""

    def _plan(self, tmp_path, mjcf=True):
        from test_robot_import_loops import make_five_bar
        return importer.analyse(make_five_bar(str(tmp_path), mjcf=mjcf))

    def test_shows_loops_and_driven_ticks(self, tmp_path, model_root):
        dlg = _dialog(self._plan(tmp_path), model_root)
        assert not dlg.table.isColumnHidden(0)
        ticks = {dlg.table.item(r, 1).text(): dlg.table.item(r, 0).checkState() == Qt.Checked
                 for r in range(dlg.table.rowCount())}
        assert ticks == {'m1': True, 'p1': False, 'm2': True, 'p2': False}
        assert dlg.loops_table.rowCount() == 1 and not dlg.loops_table.isHidden()
        assert dlg.loops_table.item(0, 0).text() == 'l_dist'
        assert dlg.add_loop_btn.isHidden()                 # loops come from the model
        assert 'five_bar.xml' in dlg.mjcf_lbl.text() and not dlg.mjcf_clear.isHidden()
        assert 'closed loop: 2 DOF' in dlg.summary.text()
        assert dlg.create_btn.isEnabled()

    def test_unticking_a_motor_blocks_create(self, tmp_path, model_root):
        dlg = _dialog(self._plan(tmp_path), model_root)
        row = [dlg.table.item(r, 1).text() for r in range(dlg.table.rowCount())].index('m2')
        dlg.table.item(row, 0).setCheckState(Qt.Unchecked)
        assert [j.name for j in dlg.plan.joints] == ['m1']
        assert not dlg.create_btn.isEnabled()

    def test_dont_use_the_model_then_add_the_loop_by_hand(self, tmp_path, model_root):
        dlg = _dialog(self._plan(tmp_path), model_root)
        dlg._set_mjcf('')
        assert dlg.plan.mjcf is None and not dlg.plan.closed_loop
        assert not dlg.add_loop_btn.isHidden()
        dlg.loop_a.setCurrentText('tip')
        dlg.loop_b.setCurrentText('r_dist')
        dlg._add_loop()
        assert dlg.plan.closed_loop and dlg.loops_table.rowCount() == 1
        assert dlg.loops_table.cellWidget(0, 4) is not None     # a Remove button
        dlg.ee_combo.setCurrentText('tip')
        assert [j.name for j in dlg.plan.joints] == ['m1', 'm2']
        dlg._remove_loop(0)
        assert not dlg.plan.closed_loop

    def test_creates_the_closed_loop_robot(self, tmp_path, model_root):
        got = []
        dlg = _dialog(self._plan(tmp_path), model_root, registered=got)
        dlg._create()
        assert got and got[0].config['kinematics_solver'] == 'pinocchio_closed_loop'
