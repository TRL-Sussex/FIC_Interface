# ── Drop zone ─────────────────────────────────────────────────────────────

class TestDropZone:

    def _drop(self, zone, path):
        mime = QMimeData()
        mime.setUrls([QUrl.fromLocalFile(path)])
        event = QDropEvent(QPoint(5, 5), Qt.CopyAction, mime, Qt.LeftButton, Qt.NoModifier)
        got = []
        zone.dropped.connect(got.append)
        zone.dropEvent(event)
        return got

    def test_accepts_urdf_folder_zip(self, tmp_path):
        from fic_studio.components.robot_drop_zone import accepts
        assert accepts(str(tmp_path))
        assert accepts('/x/robot.URDF') and accepts('/x/r.xacro') and accepts('/x/r.zip')
        assert not accepts('/x/robot.stl')

    def test_drop_emits_path(self, tmp_path):
        from fic_studio.components.robot_drop_zone import RobotDropZone
        zone = RobotDropZone()
        p = tmp_path / 'r.urdf'
        p.write_text('<robot/>')
        assert self._drop(zone, str(p)) == [str(p)]

    def test_urdf_and_model_dropped_together(self, tmp_path):
        from fic_studio.components.robot_drop_zone import RobotDropZone
        zone = RobotDropZone()
        urdf, xml = tmp_path / 'r.urdf', tmp_path / 'r.xml'
        urdf.write_text('<robot/>')
        xml.write_text('<mujoco/>')
        mime = QMimeData()
        mime.setUrls([QUrl.fromLocalFile(str(urdf)), QUrl.fromLocalFile(str(xml))])
        got = []
        zone.dropped_many.connect(got.append)
        zone.dropEvent(QDropEvent(QPoint(5, 5), Qt.CopyAction, mime, Qt.LeftButton,
                                  Qt.NoModifier))
        assert got == [[str(urdf), str(xml)]]

    def test_drop_of_other_files_ignored(self, tmp_path):
        from fic_studio.components.robot_drop_zone import RobotDropZone
        zone = RobotDropZone()
        p = tmp_path / 'mesh.stl'
        p.write_text('x')
        assert self._drop(zone, str(p)) == []


# ── Review dialog ─────────────────────────────────────────────────────────

@pytest.fixture
def model_root(tmp_path):
    root = tmp_path / 'menagerie' / 'model'
    root.mkdir(parents=True)
    return str(root)


def _dialog(plan, model_root, existing=(), registered=None):
    from fic_studio.components.robot_import_dialog import RobotImportDialog
    got = registered if registered is not None else []
    return RobotImportDialog(plan, list(existing), model_root, register=got.append)


class TestReviewDialog:

    def test_shows_what_was_found(self, tmp_path, model_root):
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root)
        assert dlg.name_edit.text() == 'Toy Arm' and dlg.id_edit.text() == 'toy_arm'
        assert dlg.ee_combo.currentText() == 'tool0'
        assert dlg.table.rowCount() == 3
        assert dlg.table.isColumnHidden(0)                    # no Driven ticks: an arm
        assert dlg.table.item(0, 4).text() == '57'            # 1 rad/s in °/s
        assert 'none' in dlg.mjcf_lbl.text() and dlg.mjcf_clear.isHidden()
        assert dlg.loops_table.isHidden() and not dlg.add_loop_btn.isHidden()
        assert 'gripper driven' in dlg.summary.text()
        assert dlg.file_combo.isHidden()                      # one description file
        assert dlg.create_btn.isEnabled()

    def test_bad_or_taken_id_blocks_create(self, tmp_path, model_root):
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root, existing=['Other'])
        dlg.id_edit.setText('9lives')
        assert not dlg.create_btn.isEnabled()
        dlg.id_edit.setText('other')
        assert not dlg.create_btn.isEnabled() and 'already exists' in dlg.id_note.text()
        dlg.id_edit.setText('fine_id')
        assert dlg.create_btn.isEnabled()

    def test_existing_folder_needs_replace_tick(self, tmp_path, model_root):
        os.makedirs(os.path.join(model_root, 'toy_arm'))
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root)
        assert not dlg.replace_cb.isHidden() and not dlg.create_btn.isEnabled()
        dlg.replace_cb.setChecked(True)
        assert dlg.create_btn.isEnabled()

    def test_changing_end_effector_updates_joints(self, tmp_path, model_root):
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root)
        dlg.ee_combo.setCurrentText('link2')
        assert dlg.table.rowCount() == 2 and dlg.plan.ee_link == 'link2'
        assert dlg.ee_source.text() == 'picked by you'

    def test_picks_between_description_files(self, tmp_path, model_root):
        pkg = make_package(str(tmp_path))
        with open(os.path.join(pkg, 'urdf', 'short_arm.urdf'), 'w') as fh:
            fh.write(arm_urdf(gripper=False, name='short_arm'))
        plan = importer.analyse(pkg)
        dlg = _dialog(plan, model_root)
        assert not dlg.file_combo.isHidden() and dlg.file_combo.count() == 2
        other = [dlg.file_combo.itemData(i) for i in range(2)
                 if dlg.file_combo.itemData(i) != plan.urdf_path][0]
        dlg.file_combo.setCurrentIndex(dlg.file_combo.findData(other))
        assert dlg.plan.urdf_path == other
        assert dlg.plan is not plan

    def test_create_registers_and_offers_next_steps(self, tmp_path, model_root):
        got = []
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root, registered=got)
        dlg._create()
        assert len(got) == 1 and got[0].robot_id == 'toy_arm'
        assert os.path.isfile(os.path.join(model_root, 'toy_arm', 'xml', 'scene.xml'))
        assert dlg._pages.currentWidget() is dlg._done_page
        dlg._finish('simulate')
        assert dlg.next_action == 'simulate'

    def test_failure_is_shown_not_raised(self, tmp_path, model_root, monkeypatch):
        def boom(*a, **k):
            raise importer.ImportError_('simulated failure')
        monkeypatch.setattr(importer, 'create_robot', boom)
        plan = importer.analyse(make_package(str(tmp_path)))
        dlg = _dialog(plan, model_root)
        dlg._create()
        assert dlg._pages.currentIndex() == 0 and dlg.cancel_btn.isEnabled()
        labels = dlg.findChildren(type(dlg.status))
        assert any('simulated failure' in lbl.text() for lbl in labels)


