"""
The quadruped built from four leg_spherical legs.

It is GENERATED by build_quad.py, so these check the properties the generator
is supposed to guarantee - naming FIC binds against, the hind-leg mirroring,
and the cable pretension that makes the drive usable under body weight.
"""

from pathlib import Path

import mujoco

import numpy as np

import pytest

HERE = Path(__file__).resolve()
FIC_ROOT = HERE.parents[4]
MODEL = (FIC_ROOT / 'fic_ws' / 'src' / 'menagerie' / 'model'
         / 'leg_spherical_quad' / 'xml' / 'leg_spherical_quad.xml')

LEGS = ('fl', 'fr', 'hl', 'hr')
AXES = ('hx', 'hy', 'hz')
CABLES = ('cable_left', 'cable_right', 'cable_back', 'cable_mid',
          'cable_loop_py', 'cable_loop_my')
#: Foot straight below the hip; the hind pair is mounted turned, so mirrored.
STAND_F = (-0.001706, -0.309506, -0.000266)
STAND_H = (-STAND_F[0], -STAND_F[1], STAND_F[2])


@pytest.fixture(scope='module')
def model():
    """The generated quadruped."""
    if not MODEL.is_file():
        pytest.skip('leg_spherical_quad not generated')
    return mujoco.MjModel.from_xml_path(str(MODEL))


def _settled(model, seconds=15.0):
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    while data.time < seconds:
        data.ctrl[:] = 0.0
        mujoco.mj_step(model, data)
    return data


def _tilt(data):
    rot = np.zeros(9)
    mujoco.mju_quat2Mat(rot, data.qpos[3:7])
    return np.degrees(np.arccos(np.clip(rot.reshape(3, 3)[2, 2], -1.0, 1.0)))


def _tendon(model, name):
    return [mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_TENDON, i)
            for i in range(model.ntendon)].index(name)


def test_it_is_a_floating_base_with_twelve_motors(model):
    """FIC addresses torq_j1..12; a quadruped needs a free base to walk."""
    names = [mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_ACTUATOR, i)
             for i in range(model.nu)]
    assert names == ['torq_j%d' % (i + 1) for i in range(12)]
    free = [j for j in range(model.njnt)
            if model.jnt_type[j] == mujoco.mjtJoint.mjJNT_FREE]
    assert len(free) == 1, 'exactly one floating base'


def test_hip_joints_are_named_as_the_locomotion_model_expects(model):
    """fic_simulation.cpp:1522 binds actuator k to joint_names[k] positionally."""
    expected = ['%s_%s' % (leg, axis) for leg in LEGS for axis in AXES]
    present = [mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, j)
               for j in range(model.njnt)]
    assert [j for j in present if j in expected] == expected


def test_every_foot_starts_under_its_own_hip(model):
    """The stand keyframe has to be a pose the robot can actually hold."""
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    mujoco.mj_forward(model, data)
    trunk = data.xpos[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, 'trunk')]
    for leg, hip_x in zip(LEGS, (0.30, 0.30, -0.30, -0.30)):
        gid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, '%s_foot_geom' % leg)
        foot = data.geom_xpos[gid] - trunk
        assert abs(foot[0] - hip_x) < 5e-3, '%s foot is not under its hip' % leg
        assert abs(foot[2] + 0.4001) < 5e-3, '%s foot is not a femur below' % leg


def test_the_hind_legs_are_mirrored(model):
    """Four identical copies put every leg's mass behind its hip.

    Unmirrored the whole-body CoM sits 30.4 mm aft of the trunk centre, the
    static load splits 44.9 / 55.1 front-hind, and the model collapses inside
    3 s of passive simulation.
    """
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    mujoco.mj_forward(model, data)
    total = model.body_mass.sum()
    com = (data.xipos * model.body_mass[:, None]).sum(axis=0) / total
    trunk = data.xpos[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, 'trunk')]
    assert abs(com[0] - trunk[0]) < 2e-3, \
        'CoM is %.4f m off centre; are the hind legs mirrored?' % (com[0] - trunk[0])


def test_it_stands_up_on_its_own(model):
    """No PD lives in the model, so this is the cables and the geometry alone."""
    data = _settled(model)
    assert data.ncon >= 4, 'not all four feet are down'
    assert _tilt(data) < 2.0, 'trunk tilted %.1f deg' % _tilt(data)
    assert data.qpos[2] > 0.38, 'trunk sank to %.3f m' % data.qpos[2]
    assert np.linalg.norm(data.qvel[:3]) < 0.05, 'still moving'


def test_every_cable_stays_taut_under_body_weight(model):
    """A slack cable is a dead zone: its drum floats with no restoring torque.

    Untensioned, four of the six cables sit at exactly zero tension at the
    loaded stand pose, two of the three drums float, and the drive stops being
    monotonic or invertible.
    """
    data = _settled(model)
    for cable in CABLES:
        for leg in LEGS:
            i = _tendon(model, '%s_%s' % (leg, cable))
            tension = ((data.ten_length[i] - model.tendon_lengthspring[i][1])
                       * model.tendon_stiffness[i])
            assert tension > 0.0, '%s_%s is slack (%.1f N)' % (leg, cable, tension)


def test_the_drums_stay_inside_the_moment_arm(model):
    """The sheave has no wrap geometry, so its arm is 40*cos(theta).

    It vanishes at |theta| ~ 1.55 rad and reverses beyond, so the drum range
    must stay well inside that or the drive saturates against its own dead zone.
    """
    for leg in LEGS:
        for drum in ('torq_j1_drum_j', 'torq_j2_drum_j', 'torq_j3_drum_j'):
            j = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT,
                                  '%s_%s' % (leg, drum))
            assert model.jnt_limited[j]
            assert model.jnt_range[j][1] < 1.2, \
                'drum range reaches the arm reversal at 1.55 rad'


def test_control_authority_is_bounded_to_the_slack_free_window(model):
    """ctrlrange is 2*T_pre*r, so no command can pull a pair's cable slack."""
    for i in range(model.nu):
        lo, hi = model.actuator_ctrlrange[i]
        assert model.actuator_ctrllimited[i]
        assert 0.0 < hi <= 9.0, 'torq_j%d ctrlrange %.1f is oversized' % (i + 1, hi)
        assert lo == -hi


def test_it_is_registered_where_the_gui_and_the_controller_look(model):
    """The GUI lists from fic_studio_robots.yaml; the nodes read robots_config."""
    yaml = pytest.importorskip('yaml')
    expected = ['%s_%s' % (leg, axis) for leg in LEGS for axis in AXES]
    for rel in ('fic_ws/src/fic_studio/fic_studio/fic_studio_robots.yaml',
                'fic_library/config/robots_config.yaml'):
        path = FIC_ROOT / rel
        if not path.is_file():
            pytest.skip('%s not reachable' % rel)
        cfg = yaml.safe_load(path.read_text())['robots']['leg_spherical_quad']
        assert cfg['num_joints'] == 12, rel
        assert cfg['joint_names'] == expected, rel
        assert len(cfg['q_home_rad']) == 12, rel
        assert cfg['mujoco_xml_path'].endswith('leg_spherical_quad.xml'), rel


def test_the_launch_map_knows_the_robot(model):
    """_resolve_xml raises and the sim dies if the name is missing."""
    launch = (FIC_ROOT / 'fic_ws' / 'src' / 'mujoco_native' / 'launch'
              / 'simulation_launch.py')
    if not launch.is_file():
        pytest.skip('launch file not reachable')
    assert 'leg_spherical_quad' in launch.read_text()
